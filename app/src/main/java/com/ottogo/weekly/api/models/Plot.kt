package com.ottogo.weekly.api.models

import android.os.Parcelable
import com.squareup.moshi.Json
import kotlinx.android.parcel.Parcelize
import kotlinx.android.parcel.RawValue
import java.util.*

@Parcelize
data class Plot(
    @Json(name = "starttime") val starttime: Date?,
    @Json(name = "name") val name: String,
    @Json(name = "id") val id: Int,
    @Json(name = "emoji") val emoji: String,
    @Json(name = "description") val description: String?,
    @Json(name = "group_id") val group_id: Int?,
    @Json(name = "relationship_id") val relationship_id: Int?,
    @Json(name = "autogenerated") val autogenerated: Boolean = false,
    @Json(name = "is_going") val is_going: Boolean = false,
    @Json(name = "invited") val invited: @RawValue List<Profile>,
    @Json(name = "going") val going: @RawValue List<Profile>,
    @Json(name = "not_going") val not_going: @RawValue List<Profile>,

    ): Parcelable
